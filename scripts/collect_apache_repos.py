#!/usr/bin/env python3
"""Sample active Apache GitHub repositories into trashpanda's JSONL contract.

Each selected repository is shallow-cloned at its current default-branch commit.
Only tracked source files that carry the ASF license header are kept, so code
bundled from other projects (under other licenses) is left out. Whole
repositories are held out for validation, so validation loss measures
generalization rather than memorization of a project.

Output (one JSONL file and one source descriptor per repository, so training
records which repository and commit every token came from):

    OUT/train/<repo>.jsonl          {"text": <file contents>} per kept file
    OUT/validation/<repo>.jsonl
    OUT/descriptors/<split>/<repo>.json
    OUT/repos.json                  the full candidate list used for sampling
    OUT/manifest.json               selection, filters, commits, counts
    OUT/prepare-args.txt            --train/--validation/--source-descriptor
                                    arguments for `trashpanda prepare`, in order

Needs only the Python standard library and git. The repository list comes from
the GitHub API (set GITHUB_TOKEN for a higher rate limit), or from --repo-list.
"""
from __future__ import annotations

import argparse
import concurrent.futures
import datetime as dt
import hashlib
import json
import os
from pathlib import Path
import random
import re
import shutil
import subprocess
import sys
import urllib.request

ASF_HEADER = "Licensed to the Apache Software Foundation"
APACHE2_HEADER = "Apache License, Version 2.0"
SOURCE_EXTENSIONS = frozenset({
    ".java", ".scala", ".kt", ".groovy", ".py", ".go", ".rs", ".c", ".cc", ".cpp", ".cxx",
    ".h", ".hh", ".hpp", ".cs", ".js", ".jsx", ".ts", ".tsx", ".rb", ".php", ".erl", ".hrl",
    ".pl", ".pm", ".lua", ".swift", ".m", ".mm", ".sh", ".bash", ".sql", ".proto", ".thrift",
    ".fbs", ".avdl", ".R", ".jl", ".d", ".clj", ".cljs",
})
SKIP_PATH = re.compile(
    r"(^|/)(vendor|vendored|third[_-]?party|3rdparty|node_modules|bower_components|generated|gen-[a-z]+|"
    r"build|target|dist|out|\.git|site-packages)(/|$)|\.min\.(js|css)$",
    re.IGNORECASE,
)
GENERATED_MARK = re.compile(r"(@generated|do not edit|automatically generated|autogenerated|generated by)", re.IGNORECASE)
SKIP_REPO_NAME = re.compile(r"(-site|-website|-www|-dist|-archive|-archives)$|^(www|site|\.github)", re.IGNORECASE)
CODE_LANGUAGES = frozenset({
    "Java", "Scala", "Kotlin", "Groovy", "Python", "Go", "Rust", "C", "C++", "C#", "JavaScript",
    "TypeScript", "Ruby", "PHP", "Erlang", "Perl", "Lua", "Swift", "Objective-C", "Shell", "R",
    "Julia", "D", "Clojure", "Thrift",
})


def log(message: str) -> None:
    print(message, file=sys.stderr, flush=True)


def fetch_repo_list(org: str, token: str | None) -> list[dict]:
    repos: list[dict] = []
    page = 1
    while True:
        url = f"https://api.github.com/orgs/{org}/repos?type=public&per_page=100&page={page}"
        request = urllib.request.Request(url, headers={"Accept": "application/vnd.github+json", "User-Agent": "trashpanda-collector"})
        if token:
            request.add_header("Authorization", f"Bearer {token}")
        with urllib.request.urlopen(request, timeout=60) as response:
            batch = json.load(response)
        if not batch:
            return repos
        repos.extend(batch)
        page += 1


def eligible(repo: dict, *, now: dt.datetime, max_age_days: int) -> bool:
    if repo.get("archived") or repo.get("fork") or repo.get("disabled") or repo.get("private"):
        return False
    if SKIP_REPO_NAME.search(repo["name"]) or repo.get("language") not in CODE_LANGUAGES:
        return False
    pushed = repo.get("pushed_at")
    if not pushed:
        return False
    age = now - dt.datetime.fromisoformat(pushed.replace("Z", "+00:00"))
    return age.days <= max_age_days and int(repo.get("size") or 0) > 0


def has_license_header(text: str, mode: str) -> bool:
    head = text[:3000]
    if ASF_HEADER in head:
        return True
    return mode == "apache2" and APACHE2_HEADER in head


_BLOCK_COMMENT = re.compile(r"\A\s*/\*.*?\*/[ \t]*\n?", re.DOTALL)
_XML_COMMENT = re.compile(r"\A\s*<!--.*?-->[ \t]*\n?", re.DOTALL)


def strip_license_header(text: str) -> str:
    """Remove a leading comment block that contains the license header.

    Keeps a shebang line. Handles /* */, <!-- -->, and runs of #, // or -- line comments.
    Returns the text unchanged if the first comment block isn't the license.
    """
    prefix = ""
    body = text
    if body.startswith("#!"):
        newline = body.find("\n")
        prefix, body = body[: newline + 1], body[newline + 1 :]
    for pattern in (_BLOCK_COMMENT, _XML_COMMENT):
        match = pattern.match(body)
        if match:
            if ASF_HEADER in match.group(0) or APACHE2_HEADER in match.group(0):
                return prefix + body[match.end():].lstrip("\n")
            return text
    lines = body.split("\n")
    marker = next((m for m in ("#", "//", "--") if lines and lines[0].lstrip().startswith(m)), None)
    if marker:
        end = 0
        while end < len(lines) and (lines[end].lstrip().startswith(marker) or (lines[end].strip() == "" and end + 1 < len(lines) and lines[end + 1].lstrip().startswith(marker))):
            end += 1
        block = "\n".join(lines[:end])
        if ASF_HEADER in block or APACHE2_HEADER in block:
            return prefix + "\n".join(lines[end:]).lstrip("\n")
    return text


def keep_file(path: str, text: str, *, license_mode: str) -> str | None:
    """Return None to keep the file, or a short reason it was dropped."""
    if SKIP_PATH.search(path):
        return "path"
    if not has_license_header(text, license_mode):
        return "license"
    if GENERATED_MARK.search(text[:2000]):
        return "generated"
    lines = text.splitlines()
    if not lines or max(len(line) for line in lines) > 2000 or len(text) / len(lines) > 300:
        return "minified"
    return None


def git(*args: str, cwd: Path | None = None) -> str:
    return subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True).stdout


def clone(name: str, org: str, dest: Path) -> str:
    if not (dest / ".git").exists():
        if dest.exists():
            shutil.rmtree(dest)
        git("clone", "--quiet", "--depth", "1", "--single-branch", "--no-tags", f"https://github.com/{org}/{name}.git", str(dest))
    return git("rev-parse", "HEAD", cwd=dest).strip()


def collect_repo(repo_dir: Path, *, license_mode: str, max_file_bytes: int, max_files: int, max_bytes: int, seed: int, strip_header: bool = True) -> tuple[list[str], dict]:
    tracked = sorted(git("ls-files", "-z", cwd=repo_dir).split("\0"))
    candidates = [p for p in tracked if p and Path(p).suffix in SOURCE_EXTENSIONS]
    random.Random(seed).shuffle(candidates)
    texts: list[str] = []
    dropped: dict[str, int] = {}
    total = 0
    for rel in candidates:
        path = repo_dir / rel
        try:
            if not path.is_file() or path.is_symlink() or path.stat().st_size > max_file_bytes:
                dropped["size"] = dropped.get("size", 0) + 1
                continue
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            dropped["unreadable"] = dropped.get("unreadable", 0) + 1
            continue
        reason = keep_file(rel, text, license_mode=license_mode)
        if reason:
            dropped[reason] = dropped.get(reason, 0) + 1
            continue
        if strip_header:
            text = strip_license_header(text)
            if not text.strip():
                dropped["empty"] = dropped.get("empty", 0) + 1
                continue
        if len(texts) >= max_files or total + len(text.encode()) > max_bytes:
            dropped["repo-cap"] = dropped.get("repo-cap", 0) + 1
            continue
        texts.append(text)
        total += len(text.encode())
    return texts, {"candidate_files": len(candidates), "kept_files": len(texts), "kept_bytes": total, "dropped": dropped}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("output", type=Path, help="output directory (must not exist, unless --resume)")
    parser.add_argument("--org", default="apache")
    parser.add_argument("--repos", type=int, default=40, help="number of repositories to sample")
    parser.add_argument("--validation-repos", type=int, help="whole repositories held out for validation (default: 10%%, at least 1)")
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--include", action="append", default=[], help="always include this repository (repeatable)")
    parser.add_argument("--repo-list", type=Path, help="JSON list of repository names or GitHub API objects to sample from instead of the API")
    parser.add_argument("--max-age-days", type=int, default=730, help="skip repositories with no push in this many days")
    parser.add_argument("--license", choices=("asf", "apache2"), default="asf", help="asf: require the ASF header; apache2: also accept other Apache-2.0 headers")
    parser.add_argument("--max-file-bytes", type=int, default=200_000)
    parser.add_argument("--max-files-per-repo", type=int, default=4000)
    parser.add_argument("--max-bytes-per-repo", type=int, default=40_000_000, help="cap so a few huge projects can't dominate")
    parser.add_argument("--keep-license-header", action="store_true", help="keep each file's leading license comment (default: strip it; the license is recorded per repository)")
    parser.add_argument("--clone-dir", type=Path, help="where to keep clones (default: OUT/clones)")
    parser.add_argument("--keep-clones", action="store_true")
    parser.add_argument("--jobs", type=int, default=4)
    parser.add_argument("--resume", action="store_true", help="reuse an existing output directory and clones")
    args = parser.parse_args(argv)

    if args.output.exists() and not args.resume:
        parser.error(f"output already exists: {args.output} (use --resume to continue)")
    if args.repos < 2:
        parser.error("--repos must be at least 2 (one for training, one for validation)")
    shutil.which("git") or parser.error("git is required")
    out = args.output
    clone_root = args.clone_dir or out / "clones"
    for sub in ("train", "validation", "descriptors/train", "descriptors/validation"):
        (out / sub).mkdir(parents=True, exist_ok=True)
    clone_root.mkdir(parents=True, exist_ok=True)
    acquired_at = dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat()

    # 1. Candidate list
    if args.repo_list:
        raw = json.loads(args.repo_list.read_text(encoding="utf-8"))
        listed = [r if isinstance(r, dict) else {"name": r} for r in raw]
        candidates = sorted({r["name"] for r in listed if not SKIP_REPO_NAME.search(r["name"])} | set(args.include))
        list_source = f"file:{args.repo_list}"
    else:
        token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
        listed = fetch_repo_list(args.org, token)
        now = dt.datetime.now(dt.timezone.utc)
        candidates = sorted({r["name"] for r in listed if eligible(r, now=now, max_age_days=args.max_age_days)} | set(args.include))
        list_source = f"https://api.github.com/orgs/{args.org}/repos"
    (out / "repos.json").write_text(json.dumps({"source": list_source, "listed": len(listed), "eligible": candidates}, indent=2) + "\n")
    log(f"{len(listed)} repositories listed, {len(candidates)} eligible")
    if len(candidates) < args.repos:
        log(f"only {len(candidates)} eligible; using all of them")

    # 2. Sample, then split whole repositories
    rng = random.Random(args.seed)
    forced = [name for name in args.include if name in candidates]
    rest = sorted(set(candidates) - set(forced))
    selected = forced + rng.sample(rest, max(0, min(args.repos, len(candidates)) - len(forced)))
    n_valid = args.validation_repos if args.validation_repos is not None else max(1, round(len(selected) * 0.1))
    validation = set(rng.sample(sorted(selected), n_valid))
    log(f"sampled {len(selected)} repositories ({n_valid} held out for validation)")

    # 3. Clone at pinned commits and keep licensed source files
    seen_hashes: set[str] = set()
    results: dict[str, dict] = {}

    def work(name: str) -> tuple[str, str, list[str], dict]:
        commit = clone(name, args.org, clone_root / name)
        texts, stats = collect_repo(clone_root / name, license_mode=args.license, max_file_bytes=args.max_file_bytes,
                                    max_files=args.max_files_per_repo, max_bytes=args.max_bytes_per_repo, seed=args.seed,
                                    strip_header=not args.keep_license_header)
        return name, commit, texts, stats

    with concurrent.futures.ThreadPoolExecutor(max_workers=args.jobs) as pool:
        futures = {pool.submit(work, name): name for name in sorted(selected)}
        for future in concurrent.futures.as_completed(futures):
            name = futures[future]
            try:
                name, commit, texts, stats = future.result()
            except subprocess.CalledProcessError as exc:
                log(f"  {name}: clone failed ({exc.stderr.strip()[:200]}); skipped")
                results[name] = {"error": "clone failed"}
                continue
            results[name] = {"commit": commit, "texts": texts, **stats}
            log(f"  {name}@{commit[:12]}: kept {stats['kept_files']} of {stats['candidate_files']} source files ({stats['kept_bytes'] / 1e6:.1f} MB)")

    # 4. Write per-repository JSONL and descriptors in a stable order, deduplicating across repositories
    manifest_repos = []
    args_lines: list[str] = []
    order = {"train": [], "validation": []}
    for name in sorted(results):
        info = results[name]
        if "error" in info:
            manifest_repos.append({"name": name, "error": info["error"]})
            continue
        split = "validation" if name in validation else "train"
        kept = []
        for text in info.pop("texts"):
            digest = hashlib.sha256(text.encode()).hexdigest()
            if digest not in seen_hashes:
                seen_hashes.add(digest)
                kept.append(text)
        info["duplicates_dropped"] = info["kept_files"] - len(kept)
        info["kept_files"] = len(kept)
        manifest_repos.append({"name": name, "split": split, **info})
        if not kept:
            log(f"  {name}: nothing kept after filtering; left out")
            continue
        jsonl = out / split / f"{name}.jsonl"
        with jsonl.open("w", encoding="utf-8") as handle:
            for text in kept:
                handle.write(json.dumps({"text": text}, ensure_ascii=False) + "\n")
        descriptor = {
            "source_id": f"github:{args.org}/{name}@{info['commit']}",
            "source": f"https://github.com/{args.org}/{name}",
            "source_revision": info["commit"],
            "selection": {
                "kind": "license-header-source-files",
                "license_header": ASF_HEADER if args.license == "asf" else f"{ASF_HEADER} | {APACHE2_HEADER}",
                "extensions": sorted(SOURCE_EXTENSIONS),
                "max_file_bytes": args.max_file_bytes,
                "max_files": args.max_files_per_repo,
                "max_bytes": args.max_bytes_per_repo,
                "seed": args.seed,
                "license_header_stripped": not args.keep_license_header,
                "files": len(kept),
            },
            "terms": "Apache-2.0",
            "evidence_state": "observed",
            "acquired_at": acquired_at,
        }
        desc_path = out / "descriptors" / split / f"{name}.json"
        desc_path.write_text(json.dumps(descriptor, indent=2) + "\n")
        order[split].append((jsonl, desc_path))

    if not order["train"] or not order["validation"]:
        log("need at least one training and one validation repository with kept files; try more --repos")
        return 1
    # prepare takes descriptors in input order: all --train inputs first, then all --validation inputs
    for jsonl, _ in order["train"]:
        args_lines.append(f"--train {jsonl.resolve()}")
    for jsonl, _ in order["validation"]:
        args_lines.append(f"--validation {jsonl.resolve()}")
    for split in ("train", "validation"):
        for _, desc in order[split]:
            args_lines.append(f"--source-descriptor {desc.resolve()}")
    (out / "prepare-args.txt").write_text("\n".join(args_lines) + "\n")

    totals = {s: {"repos": len(order[s]), "files": sum(r.get("kept_files", 0) for r in manifest_repos if r.get("split") == s),
                  "bytes": sum(r.get("kept_bytes", 0) for r in manifest_repos if r.get("split") == s)} for s in order}
    manifest = {
        "org": args.org, "acquired_at": acquired_at, "list_source": list_source, "seed": args.seed,
        "requested_repos": args.repos, "license": args.license, "totals": totals, "repos": manifest_repos,
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    if not args.keep_clones and args.clone_dir is None:
        shutil.rmtree(clone_root, ignore_errors=True)
    log(f"train: {totals['train']['repos']} repos, {totals['train']['files']} files, {totals['train']['bytes'] / 1e6:.1f} MB; "
        f"validation: {totals['validation']['repos']} repos, {totals['validation']['files']} files, {totals['validation']['bytes'] / 1e6:.1f} MB")
    print(json.dumps({"output": str(out), **totals}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
