def test_fetch_fineweb_write_splits(tmp_path):
    records = ({"text": f"doc {i}"} for i in range(10))
    assert fetch.write_splits(records, tmp_path / "fw", train_documents=3, validation_documents=2) == (3, 2)
    train = [json.loads(line)["text"] for line in (tmp_path / "fw" / "train.jsonl").read_text().splitlines()]
    valid = [json.loads(line)["text"] for line in (tmp_path / "fw" / "validation.jsonl").read_text().splitlines()]
    assert (train, valid) == (["doc 0", "doc 1", "doc 2"], ["doc 3", "doc 4"])
    with pytest.raises(RuntimeError):
        fetch.write_splits(iter([{"text": "x"}]), tmp_path / "short", train_documents=2, validation_documents=1)
    d = fetch.descriptor("HuggingFaceFW/fineweb-edu", "sample-10BT", "train", "abc", kind="validation", start=3, count=2)
    assert d["selection"]["first_record"] == 3 and d["source_id"].endswith(":validation")
