HEADER = "Licensed to the Apache Software Foundation (ASF) under one or more"


def test_strip_license_header_styles():
    assert collect.strip_license_header(f"/*\n * {HEADER}\n */\npackage a;\n") == "package a;\n"
    assert collect.strip_license_header(f"#!/bin/sh\n# {HEADER}\n# x\n\necho hi\n") == "#!/bin/sh\necho hi\n"
    assert collect.strip_license_header(f"-- {HEADER}\nSELECT 1;\n") == "SELECT 1;\n"
    untouched = "/* not a license */\nint x;\n"
    assert collect.strip_license_header(untouched) == untouched
    later = f"package a;\n/* {HEADER} */\n"
    assert collect.strip_license_header(later) == later


def test_keep_file_filters():
    good = f"/* {HEADER} */\nclass A {{}}\n"
    assert collect.keep_file("src/A.java", good, license_mode="asf") is None
    assert collect.keep_file("third_party/A.java", good, license_mode="asf") == "path"
    assert collect.keep_file("web/app.min.js", good, license_mode="asf") == "path"
    assert collect.keep_file("src/B.java", "class B {}\n", license_mode="asf") == "license"
    other = "/* Apache License, Version 2.0 */\nclass C {}\n"
    assert collect.keep_file("src/C.java", other, license_mode="asf") == "license"
    assert collect.keep_file("src/C.java", other, license_mode="apache2") is None
    assert collect.keep_file("src/G.java", f"/* {HEADER} */\n// @generated by protoc\n", license_mode="asf") == "generated"
    assert collect.keep_file("src/M.js", f"/* {HEADER} */\n" + "x" * 3000 + "\n", license_mode="asf") == "minified"


def test_eligible_repo_filter():
    now = dt.datetime(2026, 11, 25, tzinfo=dt.timezone.utc)
    base = {"name": "spark", "language": "Scala", "pushed_at": "2026-11-01T00:00:00Z", "size": 100}
    assert collect.eligible(base, now=now, max_age_days=730)
    assert not collect.eligible({**base, "archived": True}, now=now, max_age_days=730)
    assert not collect.eligible({**base, "fork": True}, now=now, max_age_days=730)
    assert not collect.eligible({**base, "name": "spark-website"}, now=now, max_age_days=730)
    assert not collect.eligible({**base, "language": "HTML"}, now=now, max_age_days=730)
    assert not collect.eligible({**base, "pushed_at": "2020-01-01T00:00:00Z"}, now=now, max_age_days=730)


@pytest.mark.skipif(shutil.which("git") is None, reason="git not installed")
def test_collect_repo_keeps_licensed_tracked_sources(tmp_path):
    repo = tmp_path / "repo"
    (repo / "src").mkdir(parents=True)
    (repo / "vendor").mkdir()
    (repo / "src" / "A.java").write_text(f"/*\n * {HEADER}\n */\nclass A {{}}\n")
    (repo / "src" / "B.java").write_text("class B {}\n")                       # no license header
    (repo / "vendor" / "C.java").write_text(f"/* {HEADER} */\nclass C {{}}\n")  # bundled path
    (repo / "README.md").write_text("not source\n")
    (repo / "src" / "Untracked.java").write_text(f"/* {HEADER} */\nclass U {{}}\n")
    subprocess.run(["git", "init", "-q", str(repo)], check=True)
    subprocess.run(["git", "-C", str(repo), "add", "src/A.java", "src/B.java", "vendor/C.java", "README.md"], check=True)
    texts, stats = collect.collect_repo(repo, license_mode="asf", max_file_bytes=10_000, max_files=10, max_bytes=10_000, seed=0)
    assert texts == ["class A {}\n"]
    assert stats["candidate_files"] == 3
    assert stats["dropped"] == {"license": 1, "path": 1}


@pytest.mark.skipif(shutil.which("git") is None, reason="git not installed")
def test_main_writes_prepare_inputs_from_local_repos(tmp_path, monkeypatch):
    clones = tmp_path / "clones"
    for name in ("alpha", "beta", "gamma"):
        repo = clones / name
        repo.mkdir(parents=True)
        (repo / "Main.java").write_text(f"/* {HEADER} */\nclass {name.title()} {{}}\n")
        subprocess.run(["git", "init", "-q", str(repo)], check=True)
        subprocess.run(["git", "-C", str(repo), "add", "."], check=True)
        subprocess.run(["git", "-C", str(repo), "-c", "user.name=t", "-c", "user.email=t@t", "commit", "-qm", "x"], check=True)
    repo_list = tmp_path / "repos.json"
    repo_list.write_text(json.dumps(["alpha", "beta", "gamma"]))
    out = tmp_path / "out"
    assert collect.main([str(out), "--repo-list", str(repo_list), "--repos", "3", "--validation-repos", "1",
                         "--clone-dir", str(clones), "--seed", "3"]) == 0
    args = (out / "prepare-args.txt").read_text().split("\n")
    trains = [a for a in args if a.startswith("--train ")]
    valids = [a for a in args if a.startswith("--validation ")]
    descs = [a for a in args if a.startswith("--source-descriptor ")]
    assert (len(trains), len(valids), len(descs)) == (2, 1, 3)
    # descriptors follow input order: train inputs first, then validation
    first = json.loads(Path(descs[0].split(" ", 1)[1]).read_text())
    assert first["source_id"].startswith(f"github:apache/{Path(trains[0].split(' ', 1)[1]).stem}@")
    assert first["terms"] == "Apache-2.0" and first["selection"]["license_header_stripped"] is True
    manifest = json.loads((out / "manifest.json").read_text())
    assert manifest["totals"]["train"]["repos"] == 2 and manifest["totals"]["validation"]["repos"] == 1


